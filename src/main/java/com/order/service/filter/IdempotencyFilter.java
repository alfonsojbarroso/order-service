package com.order.service.filter;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.buffer.DataBuffer;
import org.springframework.core.io.buffer.DataBufferFactory;
import org.springframework.data.redis.core.ReactiveStringRedisTemplate;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.server.reactive.ServerHttpRequest;
import org.springframework.http.server.reactive.ServerHttpResponse;
import org.springframework.http.server.reactive.ServerHttpResponseDecorator;
import org.springframework.stereotype.Component;
import org.springframework.web.server.ServerWebExchange;
import org.springframework.web.server.WebFilter;
import org.springframework.web.server.WebFilterChain;

import com.order.service.dto.ErrorResponseDto;
import com.order.service.enums.Status;

import reactor.core.publisher.Mono;

import static com.order.service.constants.Constants.CONCURRET_RQ_IN_PROGRESS;
import static com.order.service.constants.Constants.IDEMPOTENCY_KEY;
import static com.order.service.constants.Constants.IDEMPOTENCY_PREFIX;

import java.nio.charset.StandardCharsets;
import java.time.Duration;

@Component
public class IdempotencyFilter implements WebFilter {

    @Value("${spring.cache-ttl}")
    private Long cacheTtl;
    private final ReactiveStringRedisTemplate redisTemplate;

    public IdempotencyFilter(ReactiveStringRedisTemplate redisTemplate) {
        this.redisTemplate = redisTemplate;
    }

    @Override
    public Mono<Void> filter(ServerWebExchange exchange, WebFilterChain chain) {
        ServerHttpRequest request = exchange.getRequest();

        // Apply idempotency only to POST methods (you can include PUT if needed)
        if (!request.getMethod().matches("POST")) {
            return chain.filter(exchange);
        }

        String idempotencyKey = request.getHeaders().getFirst(IDEMPOTENCY_KEY);

        if (idempotencyKey == null || idempotencyKey.isBlank()) {
            return chain.filter(exchange);
        }

        String redisKey = IDEMPOTENCY_PREFIX + idempotencyKey;

        // Attempt to register the key in Redis atomically as "PROCESSING" (NX)
        return redisTemplate.opsForValue()
                .setIfAbsent(redisKey, Status.PROCESSING.toString(), Duration.ofMillis(cacheTtl))
                .flatMap(isNew -> {
                    if (Boolean.FALSE.equals(isNew)) {
                        // The key already exists; check its current status in Redis
                        return redisTemplate.opsForValue().get(redisKey)
                                .flatMap(cachedValue -> {
                                    ServerHttpResponse response = exchange.getResponse();

                                    // Remove null characters and surrounding whitespace
                                    String cleanValue = cachedValue != null ? cachedValue.replace("\u0000", "").trim()
                                            : "";

                                    // Always check whether it starts with PROCESSING (even if it has trailing
                                    // garbage or JSON)
                                    if (cleanValue.startsWith(Status.PROCESSING.toString())) {
                                        response.setStatusCode(HttpStatus.CONFLICT);
                                        response.getHeaders().setContentType(MediaType.APPLICATION_JSON);

                                        byte[] errorBytes = new ErrorResponseDto(HttpStatus.CONFLICT,
                                                CONCURRET_RQ_IN_PROGRESS).toString()
                                                .getBytes(StandardCharsets.UTF_8);
                                        DataBuffer errorBuffer = response.bufferFactory().wrap(errorBytes);
                                        return response.writeWith(Mono.just(errorBuffer));
                                    }

                                    // If this is a clean and valid JSON previously processed:
                                    response.setStatusCode(HttpStatus.OK);
                                    response.getHeaders().setContentType(MediaType.APPLICATION_JSON);

                                    byte[] bytes = cleanValue.getBytes(StandardCharsets.UTF_8);
                                    DataBuffer buffer = response.bufferFactory().wrap(bytes);
                                    return response.writeWith(Mono.just(buffer));
                                });
                    }

                    // If the key is new, wrap the response to intercept the body generated by the
                    // controller
                    ServerHttpResponse originalResponse = exchange.getResponse();
                    DataBufferFactory bufferFactory = originalResponse.bufferFactory();

                    ServerHttpResponseDecorator decoratedResponse = new ServerHttpResponseDecorator(originalResponse) {
                        @Override
                        public Mono<Void> writeWith(org.reactivestreams.Publisher<? extends DataBuffer> body) {
                            if (getStatusCode() != null && getStatusCode().is2xxSuccessful()) {
                                return org.springframework.core.io.buffer.DataBufferUtils.join(body)
                                        .flatMap(dataBuffer -> {
                                            byte[] content = new byte[dataBuffer.readableByteCount()];
                                            dataBuffer.read(content);
                                            org.springframework.core.io.buffer.DataBufferUtils.release(dataBuffer);

                                            // Ensure strict UTF-8 encoding to prevent character corruption
                                            String responseBody = new String(content, StandardCharsets.UTF_8);

                                            // Store the clean body in Redis
                                            return redisTemplate.opsForValue()
                                                    .set(redisKey, responseBody, cacheTtl)
                                                    .then(super.writeWith(Mono.just(bufferFactory.wrap(content))));
                                        });
                            } else {
                                return redisTemplate.delete(redisKey)
                                        .then(super.writeWith(body));
                            }
                        }
                    };

                    return chain.filter(exchange.mutate().response(decoratedResponse).build())
                            .onErrorResume(ex ->
                    // If an unhandled exception occurs, release the key in Redis
                    redisTemplate.delete(redisKey).then(Mono.error(ex)));
                });
    }

}
